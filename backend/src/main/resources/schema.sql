CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,
  perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('CLIENTE', 'EMPRESA', 'BANCO')),
  nome VARCHAR(160) NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS app.clientes (
  usuario_id BIGINT PRIMARY KEY REFERENCES app.usuarios(id) ON DELETE CASCADE,
  rg VARCHAR(30) NOT NULL,
  cpf VARCHAR(11) NOT NULL UNIQUE,
  endereco VARCHAR(255) NOT NULL,
  profissao VARCHAR(120) NOT NULL
);
CREATE TABLE IF NOT EXISTS app.empregos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES app.clientes(usuario_id) ON DELETE CASCADE,
  empregador VARCHAR(160) NOT NULL,
  rendimento NUMERIC(12,2) NOT NULL CHECK (rendimento >= 0)
);
CREATE TABLE IF NOT EXISTS app.automoveis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matricula VARCHAR(60) NOT NULL UNIQUE,
  ano INT NOT NULL CHECK (ano BETWEEN 1886 AND 2100),
  marca VARCHAR(80) NOT NULL,
  modelo VARCHAR(80) NOT NULL,
  placa VARCHAR(10) NOT NULL UNIQUE,
  proprietario_id BIGINT NOT NULL REFERENCES app.usuarios(id)
);
CREATE TABLE IF NOT EXISTS app.pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES app.clientes(usuario_id),
  automovel_id BIGINT NOT NULL REFERENCES app.automoveis(id),
  inicio DATE NOT NULL,
  fim DATE NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE','EM_ANALISE','APROVADO','RECUSADO','CONTRATADO','CANCELADO')),
  parecer TEXT,
  agente_id BIGINT REFERENCES app.usuarios(id),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fim >= inicio)
);
CREATE TABLE IF NOT EXISTS app.contratos_credito (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL UNIQUE REFERENCES app.pedidos(id),
  banco_id BIGINT NOT NULL REFERENCES app.usuarios(id),
  valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
  parcelas INT NOT NULL CHECK (parcelas > 0)
);
CREATE INDEX IF NOT EXISTS idx_pedidos_cliente ON app.pedidos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_status ON app.pedidos(status);
